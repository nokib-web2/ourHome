// A single-stroke "handwriting" font for writing in the sand: each letter is a
// few strokes (lists of points), drawn the way you'd draw it with a stick.
// Letters sit in a box from y = 0 (baseline) to y = 1 (cap height); `w` is the width.

const arc = (cx, cy, rx, ry, a0, a1, n = 12) =>
  Array.from({ length: n + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
  });

const P = (w, ...strokes) => ({ w, strokes });

