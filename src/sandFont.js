// Lay out a line of text: strokes in metres, centred on (0, 0), baseline at y = -h/2,
// with a little hand-drawn wobble so it never looks typeset.
export function layoutText(text, { height = 0.62, gap = 0.16, space = 0.34, maxWidth = 5, seed = 7 } = {}) {
  let r = seed;
  const rnd = () => ((r = (r * 16807) % 2147483647) / 2147483647);
  const chars = [...text.toUpperCase()];
  let x = 0;
  const placed = [];
  for (const ch of chars) {
    const g = GLYPHS[ch];
    if (!g) {
      x += space;
      continue;
    }
    placed.push({ g, x });
    x += g.w + gap;
  }
  const raw = Math.max(0.01, x - gap);
  const s = Math.min(height, (maxWidth / raw) * height);
  const out = [];
  for (const { g, x: gx } of placed) {
    const slant = (rnd() - 0.5) * 0.08;
    const lift = (rnd() - 0.5) * 0.06;
    const size = 1 + (rnd() - 0.5) * 0.08;
    const strokes = g.strokes.map((st) =>
      st.map(([px, py]) => [
        (gx + px * size + py * slant - raw / 2) * s + (rnd() - 0.5) * 0.012,
        (py * size - 0.5 + lift) * s + (rnd() - 0.5) * 0.012,
      ]),
    );
    out.push({ strokes, x0: (gx - raw / 2) * s, x1: (gx + g.w - raw / 2) * s });
  }
  return { glyphs: out, width: raw * s, height: s };
}
